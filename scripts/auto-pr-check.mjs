#!/usr/bin/env node

/**
 * Automatic PR checker: detects if the last PR was merged and creates a new one
 * Usage: node scripts/auto-pr-check.mjs [pr-number]
 */

const REPO = "teomotta88-cloud/trendzn";
const GITHUB_TOKEN = process.env.GITHUB_TOKEN;

if (!GITHUB_TOKEN) {
  console.error("❌ GITHUB_TOKEN not found in environment");
  process.exit(1);
}

const ghHeaders = {
  Authorization: `token ${GITHUB_TOKEN}`,
  Accept: "application/vnd.github.v3+json",
};

async function getPRStatus(prNumber) {
  try {
    const res = await fetch(`https://api.github.com/repos/${REPO}/pulls/${prNumber}`, {
      headers: ghHeaders,
    });

    if (!res.ok) {
      return null;
    }

    return await res.json();
  } catch (err) {
    console.error(`Error fetching PR #${prNumber}:`, err.message);
    return null;
  }
}

async function getLastPRNumber() {
  try {
    const res = await fetch(`https://api.github.com/repos/${REPO}/pulls?state=all&sort=created&direction=desc&per_page=1`, {
      headers: ghHeaders,
    });

    if (!res.ok) {
      return null;
    }

    const prs = await res.json();
    return prs.length > 0 ? prs[0].number : null;
  } catch (err) {
    console.error("Error fetching last PR:", err.message);
    return null;
  }
}

async function createNewPR(title, body) {
  try {
    const res = await fetch(`https://api.github.com/repos/${REPO}/pulls`, {
      method: "POST",
      headers: { ...ghHeaders, "Content-Type": "application/json" },
      body: JSON.stringify({
        title,
        body,
        head: "claude/bluserena-monitoring-bugs-xmj6d6",
        base: "main",
      }),
    });

    if (!res.ok) {
      const error = await res.text();
      console.error("Error creating PR:", error);
      return null;
    }

    return await res.json();
  } catch (err) {
    console.error("Error creating PR:", err.message);
    return null;
  }
}

async function main() {
  const prArg = process.argv[2];
  let prNumber = prArg ? parseInt(prArg, 10) : null;

  if (!prNumber) {
    console.log("📍 Finding last PR...");
    prNumber = await getLastPRNumber();
    if (!prNumber) {
      console.log("❌ No PR found");
      process.exit(1);
    }
  }

  console.log(`📋 Checking PR #${prNumber}...`);

  const pr = await getPRStatus(prNumber);
  if (!pr) {
    console.error("❌ PR not found");
    process.exit(1);
  }

  console.log(`   State: ${pr.state}`);
  console.log(`   Merged: ${pr.merged}`);

  if (!pr.merged) {
    console.log("✅ PR is still open, no new PR needed");
    process.exit(0);
  }

  console.log(`\n✅ PR #${prNumber} was merged!`);
  console.log(`   Merged at: ${pr.merged_at}`);

  // Check if there are new commits after the merge
  const branch = pr.head.ref;
  console.log(`\n🔍 Checking for new commits on branch '${branch}'...`);

  try {
    const res = await fetch(
      `https://api.github.com/repos/${REPO}/compare/main...${branch}`,
      { headers: ghHeaders }
    );

    if (!res.ok) {
      console.error("Error comparing branches");
      process.exit(1);
    }

    const comparison = await res.json();
    const newCommits = comparison.commits ? comparison.commits.length : 0;

    console.log(`   Found ${newCommits} commits ahead of main`);

    if (newCommits === 0) {
      console.log("✅ No new commits, skipping new PR");
      process.exit(0);
    }

    // Create new PR
    console.log(`\n📝 Creating new PR for ${newCommits} commit(s)...`);

    const newPR = await createNewPR(
      `chore: follow-up changes after PR #${prNumber} merge`,
      `## Follow-up PR

Previous PR: #${prNumber} was merged.

This PR contains ${newCommits} new commit(s) that were pushed after the merge.

---
_Generated by auto-pr-check.mjs_`
    );

    if (newPR) {
      console.log(`✅ New PR created: #${newPR.number}`);
      console.log(`   URL: ${newPR.html_url}`);
      process.exit(0);
    } else {
      console.error("❌ Failed to create new PR");
      process.exit(1);
    }
  } catch (err) {
    console.error("Error checking commits:", err.message);
    process.exit(1);
  }
}

main();
